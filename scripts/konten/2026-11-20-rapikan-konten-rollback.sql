## Apa itu TKDN?

TKDN (Tingkat Komponen Dalam Negeri) adalah persentase komponen produksi dalam negeri pada sebuah produk, mulai dari bahan baku, tenaga kerja, sampai alat produksinya. Nilainya dihitung dan diverifikasi oleh lembaga verifikasi independen, lalu sertifikatnya diterbitkan oleh Kementerian Perindustrian dan tercatat di situs resmi TKDN Kemenperin.

Di samping TKDN ada juga **BMP (Bobot Manfaat Perusahaan)**, yaitu nilai tambahan dari komitmen perusahaan seperti investasi, fasilitas kerja, dan program sosial. Dalam pengadaan, yang sering dilihat adalah gabungan nilai TKDN + BMP.

## Kenapa TKDN penting untuk proyek pemerintah?

Aturan pengadaan barang/jasa pemerintah (Perpres 16/2018 beserta perubahannya) mewajibkan penggunaan produk dalam negeri apabila ada penawaran produk dengan **nilai TKDN ditambah BMP paling sedikit 40%**. Artinya, untuk pekerjaan jalan lingkungan, trotoar, drainase, dan fasilitas umum yang dibiayai negara, material ber-TKDN tinggi punya posisi yang jauh lebih kuat dibanding produk tanpa sertifikat.

Bagi kontraktor, memakai material yang sudah bersertifikat juga memudahkan pemeriksaan dokumen dan mengurangi risiko temuan saat audit. Ketentuan teknis tiap paket pekerjaan tetap mengikuti dokumen pemilihan masing-masing, jadi selalu cocokkan dengan persyaratan di dokumen tender Anda.

